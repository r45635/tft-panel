//
// ⚠️ NOT FINISHED: everything on this board works except the image. The panel stays dark even
// for the DSI bridge's own hardware test pattern, which bypasses our drawing entirely, so what
// is missing is in the panel's own configuration, not in the firmware above it. What was tried,
// and what is known to be right, is written up in docs/HARDWARE.md. Its factory firmware drives
// the same panel, so the answer exists: it needs the vendor's board support code or schematic.
//
// Verified on the board itself: the chip and memory sizes, the serial console on the CH340, the
