#!/usr/bin/env python3
"""TextFromTrack mark (same geometry and colours as the companion's app icon and web top bar,
roon.app.textfromtrack.com: electron/assets/icon.svg) rendered at the panel header's size as
an LVGL RGB565A8 image in src/app/tft_icon.c.

    uv run --with pillow==11.0.0 tools/tft_icon.py [size]     # default 24 px (the header)
"""
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INK, PAPER, SIGNAL = (0x15, 0x16, 0x1A), (0xF6, 0xF4, 0xEE), (0x6D, 0xB5, 0x6D)


def render(size, ss=16):
    k = size * ss / 96   # the SVG's 96 x 96 grid, supersampled
    im = Image.new("RGBA", (size * ss, size * ss), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    R = lambda x0, y0, x1, y1, c: d.rectangle((x0 * k, y0 * k, x1 * k - 1, y1 * k - 1), fill=c + (255,))  # noqa: E731
    d.rounded_rectangle((0, 0, 96 * k - 1, 96 * k - 1), radius=22 * k, fill=INK + (255,))
    # Brackets: 6-wide square-capped strokes (the SVG paths, offset by half the stroke).
    R(19, 23, 25, 73, PAPER)       # left bar     M22 26 L22 70
    R(19, 67, 33, 73, PAPER)       # left foot    L30 70
    R(71, 23, 77, 73, PAPER)       # right bar    M74 26 L74 70
    R(63, 67, 77, 73, PAPER)       # right foot   L66 70
    R(63, 23, 77, 29, PAPER)       # right top    M74 26 L66 26
    R(36, 34, 60, 40, PAPER)       # T bar
    R(45, 34, 51, 54, PAPER)       # T stem
    for x, y, w, h in [(36, 58, 3, 6), (42, 54, 3, 14), (48, 50, 3, 22), (54, 56, 3, 10), (60, 60, 3, 3)]:
        R(x, y, x + w, y + h, SIGNAL)
    return im.resize((size, size), Image.LANCZOS)


def main():
    size = int(sys.argv[1]) if len(sys.argv) > 1 else 24
    im = render(size)
    px = list(im.getdata())
    rgb565 = bytearray()
    alpha = bytearray()
    for r, g, b, a in px:
        c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        rgb565 += bytes((c & 0xFF, c >> 8))
        alpha.append(a)
    data = rgb565 + alpha   # LV_COLOR_FORMAT_RGB565A8: the RGB565 plane, then the alpha plane
    lines = [", ".join(f"0x{v:02x}" for v in data[i:i + 16]) for i in range(0, len(data), 16)]
    out = os.path.join(ROOT, "src/app/tft_icon.c")
    with open(out, "w") as f:
        f.write(f"""// Generated by tools/tft_icon.py: the TextFromTrack mark, {size} x {size}, RGB565A8.
// Same drawing as the companion's app icon, so the panel and the desktop UI look related.
#include <lvgl.h>

static const uint8_t TFT_ICON_DATA[] = {{
    {(","+chr(10)+"    ").join(lines)}
}};

const lv_image_dsc_t tft_icon = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565A8,
        .flags = 0,
        .w = {size},
        .h = {size},
        .stride = {size * 2},
    }},
    .data_size = sizeof TFT_ICON_DATA,
    .data = TFT_ICON_DATA,
}};
""")
    im.resize((size * 8, size * 8), Image.NEAREST).save(os.path.join(ROOT, ".pio", "tft_icon_preview.png"))
    print(out, len(data), "bytes")


if __name__ == "__main__":
    main()
