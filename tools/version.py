# PlatformIO pre-script: writes src/generated/version.cpp with the firmware version taken
# from git ("v0.1.0", "v0.1.0-3-gabc1234", "v0.1.0-dirty"…). Only that file recompiles when
# the version changes (a global -D define would rebuild LVGL and the framework).
import os
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

root = env.subst("$PROJECT_DIR")  # noqa: F821


def describe():
    try:
        v = subprocess.check_output(["git", "describe", "--tags", "--always", "--dirty"], cwd=root,
                                    stderr=subprocess.DEVNULL, text=True).strip()
    except Exception:
        return "v0.0.0-unknown"
    # No tag yet: "abc1234[-dirty]" → "v0.0.0-gabc1234[-dirty]" so it still parses as a version.
    return v if v.startswith("v") else "v0.0.0-g" + v


# TFT_FW_VERSION=v0.1.0-test pretends to be an older version, to test an update end to end.
version = os.environ.get("TFT_FW_VERSION") or describe()
path = os.path.join(root, "src", "generated", "version.cpp")
text = ('// Generated by tools/version.py at build time. Do not edit, not in git.\n'
        '#include "../version.h"\n\n'
        'const char *const FW_VERSION = "%s";\n' % version)
os.makedirs(os.path.dirname(path), exist_ok=True)
old = open(path).read() if os.path.exists(path) else ""
if old != text:
    with open(path, "w") as f:
        f.write(text)
print("TFT Panel firmware version:", version)
